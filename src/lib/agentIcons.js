const ICON_ALIASES = {
  Github: GitHubIcon,
  GitHub: GitHubIcon,
}

const hasOwn = (object, key) => Object.prototype.hasOwnProperty.call(object, key)

export function resolveAgentIcon(name) {
  if (!name) return AGENT_ICONS.Bot
  if (hasOwn(ICON_ALIASES, name)) return ICON_ALIASES[name]
  return hasOwn(AGENT_ICONS, name) ? AGENT_ICONS[name] : AGENT_ICONS.Bot
}

export function isKnownAgentIcon(name) {
  if (!name) return false
  return hasOwn(ICON_ALIASES, name) || (hasOwn(AGENT_ICONS, name) && Boolean(AGENT_ICONS[name]))
}
